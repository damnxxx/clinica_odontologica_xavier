CREATE TABLE clientes (
    id UUID PRIMARY KEY, nome VARCHAR(120) NOT NULL, cpf VARCHAR(14) NOT NULL UNIQUE,
    email VARCHAR(160) NOT NULL, telefone VARCHAR(20) NOT NULL, data_nascimento DATE, observacoes_clinicas VARCHAR(1000)
);
CREATE TABLE enderecos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id UUID NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
    logradouro VARCHAR(120) NOT NULL, numero VARCHAR(20) NOT NULL, complemento VARCHAR(80),
    bairro VARCHAR(80) NOT NULL, cidade VARCHAR(80) NOT NULL, estado CHAR(2) NOT NULL, cep VARCHAR(9) NOT NULL
);
CREATE INDEX idx_enderecos_cliente_id ON enderecos(cliente_id);
CREATE TABLE usuarios (
    id UUID PRIMARY KEY, nome VARCHAR(120) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL, ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE profissionais (
    id UUID PRIMARY KEY, nome VARCHAR(120) NOT NULL, especialidade VARCHAR(120) NOT NULL,
    formacao VARCHAR(240) NOT NULL, experiencia_anos INTEGER NOT NULL, biografia VARCHAR(1000) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE servicos (
    id UUID PRIMARY KEY, nome VARCHAR(120) NOT NULL UNIQUE, descricao VARCHAR(500) NOT NULL,
    duracao_minutos INTEGER NOT NULL, ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE agendamentos (
    id UUID PRIMARY KEY, paciente_id UUID REFERENCES clientes(id) ON DELETE SET NULL,
    profissional_id UUID NOT NULL REFERENCES profissionais(id), servico_id UUID NOT NULL REFERENCES servicos(id),
    paciente_nome VARCHAR(120) NOT NULL, paciente_email VARCHAR(160) NOT NULL, paciente_telefone VARCHAR(20) NOT NULL,
    inicio TIMESTAMP NOT NULL, fim TIMESTAMP NOT NULL, status VARCHAR(20) NOT NULL, observacao VARCHAR(500),
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE disponibilidade_profissional (
    id UUID PRIMARY KEY, profissional_id UUID NOT NULL REFERENCES profissionais(id) ON DELETE CASCADE,
    dia_semana SMALLINT NOT NULL, inicio TIME NOT NULL, fim TIME NOT NULL,
    intervalo_minutos INTEGER NOT NULL, ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE bloqueios_agenda (
    id UUID PRIMARY KEY, profissional_id UUID NOT NULL REFERENCES profissionais(id) ON DELETE CASCADE,
    inicio TIMESTAMP NOT NULL, fim TIMESTAMP NOT NULL, motivo VARCHAR(250), criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
